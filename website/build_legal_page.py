def one(pattern, text, what):
    found = re.findall(pattern, text, re.S)
    if len(found) != 1:
        raise SystemExit(f"refused: expected exactly one {what} in the notices, found {len(found)}")
    return found[0]


def build(source):
    meta = one(r'<p class="meta">(.*?)</p>', source, '<p class="meta">')
    index = one(r'(<nav aria-label="Components">.*?</nav>)', source, "component index <nav>")
    sections = one(r"<main>\n(.*?)</main>", source, "<main>")
    page = HEAD.replace("{style}", STYLE).replace("{meta}", meta) + index + "\n" + sections + FOOT
    # Every licence text must come through unmodified.
    if PRE.findall(page) != PRE.findall(source) or not PRE.findall(source):
        raise SystemExit("refused: the licence texts in the output differ from the source")
    return page


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--notices", default=DEFAULT_NOTICES)
    p.add_argument("--out", default=DEFAULT_OUT)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    with open(a.notices, encoding="utf-8", newline="") as f:
        page = build(f.read())
    if a.check:
        try:
            with open(a.out, encoding="utf-8", newline="") as f:
                same = f.read() == page
        except FileNotFoundError:
            same = False
        print(f"{a.out} is {'up to date' if same else 'out of date'}")
        return 0 if same else 1
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="") as f:
        f.write(page)
    print(f"wrote {a.out} ({len(PRE.findall(page))} notices, {len(page)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
