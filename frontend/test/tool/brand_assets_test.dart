import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';

/// Width, height and PNG color type (2 = RGB, 6 = RGBA) from the IHDR chunk.
(int, int, int) _png(String path) {
  final bytes = File(path).readAsBytesSync();
  expect(bytes.sublist(0, 8), [
    0x89,
    0x50,
    0x4E,
    0x47,
    0x0D,
    0x0A,
    0x1A,
    0x0A,
  ], reason: '$path is not a PNG');
  final h = ByteData.sublistView(bytes, 16, 29);
  return (h.getUint32(0), h.getUint32(4), h.getUint8(9));
}

const _rgb = 2;
const _rgba = 6;

void main() {
  // Generated by tool/generate_brand_assets.dart; these checks keep the
  // launcher/splash artwork complete and store-valid.

  test('iOS app icons: every Contents.json size, opaque (no alpha)', () {
    const dir = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';
    final json =
        jsonDecode(File('$dir/Contents.json').readAsStringSync())
            as Map<String, dynamic>;
    final images = (json['images'] as List).cast<Map<String, dynamic>>();
    expect(images, isNotEmpty);
    for (final img in images) {
      final file = '$dir/${img['filename']}';
      final points = double.parse((img['size'] as String).split('x').first);
      final scale = int.parse((img['scale'] as String).replaceAll('x', ''));
      final (w, h, type) = _png(file);
      expect(w, (points * scale).round(), reason: file);
      expect(h, w, reason: file);
      expect(type, _rgb, reason: '$file must not have an alpha channel');
    }
    // The App Store icon is the committed master artwork.
    expect(
      File('$dir/Icon-App-1024x1024@1x.png').readAsBytesSync(),
      File('assets/branding/app_icon_1024.png').readAsBytesSync(),
    );
  });

  test('iOS launch screen: crest image + light/dark brand color', () {
    const dir = 'ios/Runner/Assets.xcassets/LaunchCrest.imageset';
    for (final (name, scale) in [
      ('LaunchCrest.png', 1),
      ('LaunchCrest@2x.png', 2),
      ('LaunchCrest@3x.png', 3),
    ]) {
      final (w, h, type) = _png('$dir/$name');
      // 184 x 232 pt canvas (crest 132 pt wide + room for its shadow).
      expect((w, h), (184 * scale, 232 * scale));
      expect(type, _rgba);
    }
    final storyboard = File(
      'ios/Runner/Base.lproj/LaunchScreen.storyboard',
    ).readAsStringSync();
    expect(storyboard, contains('image="LaunchCrest"'));
    expect(storyboard, contains('name="LaunchBackground"'));
    final colors = File(
      'ios/Runner/Assets.xcassets/LaunchBackground.colorset/Contents.json',
    ).readAsStringSync();
    expect(colors, contains('"value" : "dark"'));
  });

  test('Android launcher icons: legacy, round, adaptive + monochrome', () {
    const res = 'android/app/src/main/res';
    const densities = {
      'mdpi': 1.0,
      'hdpi': 1.5,
      'xhdpi': 2.0,
      'xxhdpi': 3.0,
      'xxxhdpi': 4.0,
    };
    for (final d in densities.entries) {
      final legacy = (48 * d.value).round();
      final layer = (108 * d.value).round();
      final logoW = (184 * d.value).round();
      final logoH = (232 * d.value).round();
      final m = '$res/mipmap-${d.key}';
      expect(_png('$m/ic_launcher.png'), (legacy, legacy, _rgba));
      expect(_png('$m/ic_launcher_round.png'), (legacy, legacy, _rgba));
      expect(_png('$m/ic_launcher_foreground.png'), (layer, layer, _rgba));
      expect(_png('$m/ic_launcher_background.png'), (layer, layer, _rgb));
      expect(_png('$m/ic_launcher_monochrome.png'), (layer, layer, _rgba));
      expect(_png('$res/drawable-${d.key}/launch_logo.png'), (
        logoW,
        logoH,
        _rgba,
      ));
      final splash = (288 * d.value).round();
      expect(_png('$res/drawable-${d.key}/splash_icon.png'), (
        splash,
        splash,
        _rgba,
      ));
    }
    for (final name in ['ic_launcher', 'ic_launcher_round']) {
      final xml = File('$res/mipmap-anydpi-v26/$name.xml').readAsStringSync();
      expect(xml, contains('@mipmap/ic_launcher_foreground'));
      expect(xml, contains('@mipmap/ic_launcher_background'));
      expect(xml, contains('<monochrome'));
    }
    final manifest = File(
      'android/app/src/main/AndroidManifest.xml',
    ).readAsStringSync();
    expect(manifest, contains('android:icon="@mipmap/ic_launcher"'));
    expect(manifest, contains('android:roundIcon="@mipmap/ic_launcher_round"'));
  });

  test('Android splash: branded before and after Android 12, light + dark', () {
    const res = 'android/app/src/main/res';
    for (final dir in ['drawable', 'drawable-v21']) {
      final xml = File('$res/$dir/launch_background.xml').readAsStringSync();
      expect(xml, contains('@color/launch_background'));
      expect(xml, contains('@drawable/launch_logo'));
    }
    for (final dir in ['values-v31', 'values-night-v31']) {
      final xml = File('$res/$dir/styles.xml').readAsStringSync();
      expect(xml, contains('android:windowSplashScreenBackground'));
      expect(
        xml,
        contains(
          '<item name="android:windowSplashScreenAnimatedIcon">'
          '@drawable/splash_icon</item>',
        ),
      );
    }
  });
}
