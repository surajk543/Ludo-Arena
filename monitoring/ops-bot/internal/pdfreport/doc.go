// Package pdfreport renders the hourly status, the daily KPI digest and
// (optionally) alerts as A4 PDF reports with embedded PNG charts. It uses
// go-pdf/fpdf (pure Go) with the standard Helvetica font; text is encoded as
// cp1252, so labels stay within that character set.
package pdfreport

import (
	"bytes"
	"errors"
	"fmt"
	"strings"
	"time"

	"codeberg.org/go-pdf/fpdf"

	"ludoarena/opsbot/internal/charts"
)

const (
	pageW, pageH = 210.0, 297.0
	margin       = 15.0
	contentW     = pageW - 2*margin
	chartH       = 57.0
	gap          = 3.0
)

type rgb struct{ r, g, b int }

var (
	colInk     = rgb{0x1F, 0x29, 0x37}
	colMuted   = rgb{0x6B, 0x72, 0x80}
	colLight   = rgb{0xF3, 0xF4, 0xF6}
	colBorder  = rgb{0xE5, 0xE7, 0xEB}
	colBand    = rgb{0x11, 0x18, 0x27}
	colAccent  = rgb{0x25, 0x63, 0xEB}
	colRed     = rgb{0xDC, 0x26, 0x26}
	colOrange  = rgb{0xEA, 0x58, 0x0C}
	colGreen   = rgb{0x16, 0xA3, 0x4A}
	colBandSub = rgb{0xD1, 0xD5, 0xDB}
)

// Options tune the output (tests disable compression to inspect text).
type Options struct {
	NoCompression bool
}

type doc struct {
	pdf     *fpdf.Fpdf
	tr      func(string) string
	imgN    int
	running string
}

func newDoc(title, subtitle, running string, accent rgb, created time.Time, opt Options) *doc {
	p := fpdf.New("P", "mm", "A4", "")
	d := &doc{pdf: p, tr: p.UnicodeTranslatorFromDescriptor(""), running: running}
	p.SetCompression(!opt.NoCompression)
	p.SetMargins(margin, margin, margin)
	p.SetAutoPageBreak(true, margin+4)
	p.SetTitle(title, true)
	p.SetSubject(subtitle, true)
	p.SetCreator("Ludo Arena ops bot", true)
	p.SetProducer("ludoarena/opsbot", true)
	p.SetCreationDate(created)
	p.SetModificationDate(created)
	p.AliasNbPages("{nb}")
	p.SetHeaderFuncMode(func() {
		if p.PageNo() == 1 {
			return
		}
		d.font("", 8, colMuted)
		p.SetXY(margin, 8)
		p.CellFormat(contentW, 5, d.tr(d.running), "", 0, "L", false, 0, "")
		d.draw(colBorder)
		p.SetLineWidth(0.2)
		p.Line(margin, 13.5, pageW-margin, 13.5)
		p.SetY(margin + 2)
	}, false)
	p.SetFooterFunc(func() {
		p.SetY(-11)
		d.font("", 7.5, colMuted)
		p.CellFormat(contentW/2, 5, d.tr("Generated by the Ludo Arena ops bot"), "", 0, "L", false, 0, "")
		p.CellFormat(contentW/2, 5, fmt.Sprintf("Page %d/{nb}", p.PageNo()), "", 0, "R", false, 0, "")
	})
	p.AddPage()
	d.band(title, subtitle, accent)
	return d
}

func (d *doc) font(style string, size float64, c rgb) {
	d.pdf.SetFont("Helvetica", style, size)
	d.pdf.SetTextColor(c.r, c.g, c.b)
}

func (d *doc) fill(c rgb) { d.pdf.SetFillColor(c.r, c.g, c.b) }
func (d *doc) draw(c rgb) { d.pdf.SetDrawColor(c.r, c.g, c.b) }

// band draws the first-page title band.
func (d *doc) band(title, subtitle string, accent rgb) {
	p := d.pdf
	d.fill(colBand)
	p.Rect(0, 0, pageW, 27, "F")
	d.fill(accent)
	p.Rect(0, 27, pageW, 1.6, "F")
	p.SetXY(margin, 7)
	d.font("B", 17, rgb{0xFF, 0xFF, 0xFF})
	p.CellFormat(contentW, 8, d.tr(title), "", 1, "L", false, 0, "")
	p.SetX(margin)
	d.font("", 10, colBandSub)
	p.CellFormat(contentW, 6, d.tr(subtitle), "", 1, "L", false, 0, "")
	p.SetY(35)
}

// ensure starts a new page unless h millimetres fit below the cursor.
func (d *doc) ensure(h float64) {
	if d.pdf.GetY()+h > pageH-margin-6 {
		d.pdf.AddPage()
	}
}

func (d *doc) newPage() { d.pdf.AddPage() }

func (d *doc) section(title string) {
	d.ensure(16)
	p := d.pdf
	p.Ln(2)
	d.font("B", 11.5, colInk)
	p.SetX(margin)
	p.CellFormat(contentW, 6.5, d.tr(title), "", 1, "L", false, 0, "")
	d.draw(colAccent)
	p.SetLineWidth(0.5)
	y := p.GetY()
	p.Line(margin, y, margin+18, y)
	p.Ln(2.5)
}

type tile struct {
	Label, Value, Sub string
	Accent            *rgb
}

// tiles draws KPI tiles, four per row.
func (d *doc) tiles(items []tile) {
	const perRow, h = 4, 21.0
	w := (contentW - gap*(perRow-1)) / perRow
	p := d.pdf
	for i := 0; i < len(items); i += perRow {
		d.ensure(h + gap)
		y := p.GetY()
		for j := 0; j < perRow && i+j < len(items); j++ {
			t := items[i+j]
			x := margin + float64(j)*(w+gap)
			d.fill(colLight)
			p.RoundedRect(x, y, w, h, 1.6, "1234", "F")
			if t.Accent != nil {
				d.fill(*t.Accent)
				p.Rect(x, y+2, 0.9, h-4, "F")
			}
			p.SetXY(x+3, y+2.2)
			d.font("", 7.5, colMuted)
			p.CellFormat(w-5, 4, d.tr(fit(p, d.tr, t.Label, w-5)), "", 0, "L", false, 0, "")
			p.SetXY(x+3, y+6.8)
			d.font("B", 15, colInk)
			p.CellFormat(w-5, 7.5, d.tr(t.Value), "", 0, "L", false, 0, "")
			if t.Sub != "" {
				p.SetXY(x+3, y+14.6)
				d.font("", 7, colMuted)
				p.CellFormat(w-5, 4, d.tr(fit(p, d.tr, t.Sub, w-5)), "", 0, "L", false, 0, "")
			}
		}
		p.SetY(y + h + gap)
	}
}

// fit shortens s with an ellipsis until it fits w millimetres.
func fit(p *fpdf.Fpdf, tr func(string) string, s string, w float64) string {
	if p.GetStringWidth(tr(s)) <= w {
		return s
	}
	r := []rune(s)
	for len(r) > 1 && p.GetStringWidth(tr(string(r)+"…")) > w {
		r = r[:len(r)-1]
	}
	return string(r) + "…"
}

type column struct {
	Title string
	W     float64 // fraction of the content width
	Align string  // L, R, C
}

// table draws a simple striped table.
func (d *doc) table(cols []column, rows [][]string) {
	p := d.pdf
	const rh = 6.0
	d.ensure(rh * float64(min(len(rows), 4)+1))
	header := func() {
		d.fill(colLight)
		d.font("B", 8.5, colMuted)
		p.SetX(margin)
		for _, c := range cols {
			p.CellFormat(c.W*contentW, rh, d.tr(c.Title), "", 0, align(c.Align), true, 0, "")
		}
		p.Ln(rh)
	}
	header()
	for i, r := range rows {
		if p.GetY()+rh > pageH-margin-6 {
			p.AddPage()
			header()
		}
		if i%2 == 1 {
			d.fill(rgb{0xFA, 0xFA, 0xFB})
		} else {
			d.fill(rgb{0xFF, 0xFF, 0xFF})
		}
		d.font("", 8.5, colInk)
		p.SetX(margin)
		for j, c := range cols {
			v := ""
			if j < len(r) {
				v = r[j]
			}
			w := c.W * contentW
			p.CellFormat(w, rh, d.tr(fit(p, d.tr, v, w-2)), "", 0, align(c.Align), true, 0, "")
		}
		p.Ln(rh)
	}
	d.draw(colBorder)
	p.SetLineWidth(0.2)
	p.Line(margin, p.GetY(), pageW-margin, p.GetY())
	p.Ln(gap)
}

func align(a string) string {
	if a == "" {
		return "L"
	}
	return a
}

// chart embeds a PNG chart, or a note box when there is no data.
func (d *doc) chart(png []byte, err error, h float64, emptyNote string) {
	if err != nil || len(png) == 0 {
		if err != nil && !errors.Is(err, charts.ErrNoData) {
			emptyNote += " (" + err.Error() + ")"
		}
		d.notice(emptyNote)
		return
	}
	d.ensure(h + gap)
	p := d.pdf
	d.imgN++
	name := fmt.Sprintf("chart%d", d.imgN)
	opts := fpdf.ImageOptions{ImageType: "PNG", ReadDpi: false}
	p.RegisterImageOptionsReader(name, opts, bytes.NewReader(png))
	y := p.GetY()
	p.ImageOptions(name, margin, y, contentW, h, false, opts, 0, "")
	p.SetY(y + h + gap)
}

// halfW is the width of one of two side-by-side charts.
const halfW = (contentW - gap) / 2

// chartPair embeds two half-width charts side by side; a chart without
// data is replaced by a short note in its half.
func (d *doc) chartPair(left, right []byte, lerr, rerr error, h float64, lnote, rnote string) {
	d.ensure(h + gap)
	p := d.pdf
	y := p.GetY()
	for i, c := range []struct {
		png  []byte
		err  error
		note string
	}{{left, lerr, lnote}, {right, rerr, rnote}} {
		x := margin + float64(i)*(halfW+gap)
		if c.err != nil || len(c.png) == 0 {
			d.fill(colLight)
			p.RoundedRect(x, y, halfW, h, 1.5, "1234", "F")
			d.font("", 9, colMuted)
			p.SetXY(x+4, y+h/2-3)
			p.MultiCell(halfW-8, 4.6, d.tr(c.note), "", "C", false)
			continue
		}
		d.imgN++
		name := fmt.Sprintf("chart%d", d.imgN)
		opts := fpdf.ImageOptions{ImageType: "PNG"}
		p.RegisterImageOptionsReader(name, opts, bytes.NewReader(c.png))
		p.ImageOptions(name, x, y, halfW, h, false, opts, 0, "")
	}
	p.SetY(y + h + gap)
}

// notice draws a light box with a one-paragraph message.
func (d *doc) notice(text string) {
	p := d.pdf
	d.font("", 9, colMuted)
	lines := p.SplitText(d.tr(text), contentW-8)
	h := float64(len(lines))*4.6 + 6
	d.ensure(h + gap)
	y := p.GetY()
	d.fill(colLight)
	d.draw(colBorder)
	p.SetLineWidth(0.2)
	p.RoundedRect(margin, y, contentW, h, 1.5, "1234", "FD")
	p.SetXY(margin+4, y+3)
	for _, l := range lines {
		p.SetX(margin + 4)
		p.CellFormat(contentW-8, 4.6, l, "", 1, "L", false, 0, "")
	}
	p.SetY(y + h + gap)
}

// note writes a small muted paragraph.
func (d *doc) note(text string) {
	if strings.TrimSpace(text) == "" {
		return
	}
	p := d.pdf
	d.font("", 8, colMuted)
	p.SetX(margin)
	p.MultiCell(contentW, 4.2, d.tr(text), "", "L", false)
	p.Ln(1)
}

// line writes one line of body text.
func (d *doc) line(text string) {
	p := d.pdf
	d.ensure(6)
	d.font("", 9.5, colInk)
	p.SetX(margin)
	p.MultiCell(contentW, 5, d.tr(text), "", "L", false)
}

func (d *doc) bytes() ([]byte, error) {
	var buf bytes.Buffer
	if err := d.pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("pdf: %w", err)
	}
	return buf.Bytes(), nil
}
